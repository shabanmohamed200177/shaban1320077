/**
 * ========================================
 * 7. منطق الأعمال
 * ========================================
 * 
 * 7.1 حساب المبلغ المتبقي:
 * remaining_balance = cod_amount - paid_amount
 * 
 * 7.2 التحقق من صحة الدفعة:
 * - المبلغ > 0
 * - المبلغ <= المتبقي
 * - الشحنة موجودة
 * - المستخدم له صلاحية
 * 
 * 7.3 تحديث حالة الدفع:
 * - unpaid: المتبقي = cod_amount
 * - partial_paid: 0 < المتبقي < cod_amount
 * - fully_paid: المتبقي = 0
 * 
 * 7.4 تغيير حالة الشحنة:
 * - fully_paid: status = 5 (تم الدفع بنجاح)
 * - partial_paid: status = 6 (تم الدفع جزئي)
 * - unpaid: status = 4 (تم التسليم بنجاح)
 */

