/**
 * ========================================
 * 5. تصميم قاعدة البيانات
 * ========================================
 * 
 * 5.1 الأعمدة الموحدة في جدول parcels:
 * - cod_amount: مبلغ التحصيل عند الاستلام
 * - paid_amount: المبلغ المدفوع
 * - remaining_balance: المبلغ المتبقي
 * - payment_status: حالة الدفع (unpaid, partial_paid, fully_paid)
 * - last_payment_date: تاريخ آخر دفعة
 * - payment_updated_by: من قام بتحديث الدفع
 * - payment_updated_at: وقت آخر تحديث للدفع
 * 
 * 5.2 جدول customer_payments (موجود):
 * - id: معرف فريد
 * - parcel_id: معرف الشحنة
 * - payment_amount: مبلغ الدفعة
 * - payment_date: تاريخ الدفع
 * - payment_method: طريقة الدفع
 * - payment_note: ملاحظة الدفع
 * - collected_by: من قام بالتحصيل
 * - ip_address: عنوان IP
 * - user_type: نوع المستخدم (courier, admin, agent)
 * - user_id: معرف المستخدم
 * 
 * 5.3 جدول operation_logs (جديد):
 * - id: معرف فريد
 * - user_id: معرف المستخدم
 * - user_type: نوع المستخدم
 * - action: العملية المنجزة
 * - parcel_id: معرف الشحنة
 * - details: تفاصيل العملية
 * - ip_address: عنوان IP
 * - created_at: وقت العملية
 */

